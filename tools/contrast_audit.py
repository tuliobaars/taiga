#!/usr/bin/env python3
"""WCAG 2.x contrast of each app's text tokens on its surfaces (light and dark), from the extracted tokens.
Writes inst/extdata/tokens/contrast.md (the R equivalent is taiga_contrast_audit()). AA body text needs 4.5:1, large text (>= 24px, or >= 18.66px bold) and UI needs 3:1."""
import json, os
HERE = os.path.dirname(os.path.abspath(__file__)); TOK = os.path.join(os.path.dirname(HERE), "inst", "extdata", "tokens")
def lum(h):
    h = h.lstrip("#"); h = "".join(c * 2 for c in h) if len(h) == 3 else h[:6]
    c = [int(h[i:i + 2], 16) / 255 for i in (0, 2, 4)]; c = [x / 12.92 if x <= .04045 else ((x + .055) / 1.055) ** 2.4 for x in c]
    return .2126 * c[0] + .7152 * c[1] + .0722 * c[2]
def ratio(a, b):
    la, lb = lum(a), lum(b); return (max(la, lb) + .05) / (min(la, lb) + .05)
def grade(r): return "AAA" if r >= 7 else "AA" if r >= 4.5 else "AA large/UI" if r >= 3 else "fail"
def cp(app): return json.load(open(os.path.join(TOK, app + ".json")))["custom_properties"]
rows = []
def add(app, theme, fg_name, fg, bg_name, bg): rows.append((app, theme, fg_name, fg, bg_name, bg, ratio(fg, bg)))
q = cp("QuantSkill"); ql, qd = q[".qs"], q['.qs[data-theme="dark"]']
for t, s in (("light", ql), ("dark", dict(ql, **qd))):
    for f in ("--text", "--text-2", "--text-3"):
        for b in ("--bg", "--bg-3"): add("QuantSkill", t, f, s[f], b, s[b])
    add("QuantSkill", t, "#fff on --accent", "#ffffff", "--accent", s["--accent"])
d = cp("DirectoR")[":root"]
for f in ("--text", "--muted", "--dim"): add("DirectoR", "dark", f, d[f], "--bg", d["--bg"])
add("DirectoR", "dark", "#fff on --a1 (gradient start)", "#ffffff", "--a1", d["--a1"]); add("DirectoR", "dark", "#fff on --a2 (gradient mid)", "#ffffff", "--a2", d["--a2"])
r = cp("RockShiny")[".rs-hw"]
for f in ("--rs-text", "--rs-muted"): add("RockShiny", "dark", f, r[f], "page bg #0b0d13", "#0b0d13")
add("RockShiny", "dark", "#1a1206 on --rs-accent", "#1a1206", "--rs-accent", r["--rs-accent"])
l = cp("lumenJourney"); base = l[".lumen-story"]
for t, s in (("dark (default)", dict(base, **l['.lumen-story[data-theme="dark"]'])), ("light (paper)", dict(base, **l['.lumen-story:not([data-theme="dark"])']))):
    for f in ("--ls-text", "--ls-text-2", "--ls-text-3"):
        for b in ("--ls-bg", "--ls-card"): add("lumenJourney", t, f, s[f], b, s[b])
    add("lumenJourney", t, "--ls-accent on --ls-bg", s["--ls-accent"], "--ls-bg", s["--ls-bg"])
for app in ("teal_neue", "BlockR"):
    c = cp(app)
    for t, s in (("light", c['html:not([data-bs-theme="dark"])']), ("dark", c['html[data-bs-theme="dark"]'])):
        for f in ("--tn-ink", "--tn-ink-2", "--tn-ink-3", "--tn-ink-4"):
            for b in ("--tn-panel", "--tn-canvas"): add(app, t, f, s[f], b, s[b])
        add(app, t, "--tn-on-accent on --tn-accent", s["--tn-on-accent"], "--tn-accent", s["--tn-accent"])
        add(app, t, "--tn-accent-ink on --tn-panel", s["--tn-accent-ink"], "--tn-panel", s["--tn-panel"])
with open(os.path.join(TOK, "contrast.md"), "w") as f:
    f.write("# Contrast audit\n\nGenerated by `tools/contrast_audit.py` from the extracted tokens. WCAG 2.x: AA body text 4.5:1; large text and UI components 3:1.\n\n")
    f.write("| App | Theme | Foreground | | Background | | Ratio | Grade |\n|---|---|---|---|---|---|---:|---|\n")
    for a, t, fn, fg, bn, bg, rr in rows: f.write("| %s | %s | `%s` | `%s` | `%s` | `%s` | %.2f | %s |\n" % (a, t, fn, fg, bn, bg, rr, grade(rr)))
fails = [x for x in rows if x[6] < 4.5]
print(len(rows), "pairs;", len(fails), "below 4.5:1:")
for a, t, fn, fg, bn, bg, rr in fails: print("  %-13s %-15s %-32s on %-16s %.2f %s" % (a, t, fn, bn, rr, grade(rr)))
