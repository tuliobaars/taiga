#!/usr/bin/env python3
"""Write inst/css/neue-tokens.css: the Neue token layers, taken verbatim (custom properties only) from
teal_neue/inst/www/teal_neue.css, plus BlockR's "lifted slate" dark palette as an opt-in alternative
(html[data-bs-theme="dark"][data-tn-dark="slate"]). Re-run after teal_neue's tokens change."""
import json, os, re
HERE = os.path.dirname(os.path.abspath(__file__)); DS = os.path.dirname(HERE); WS = os.path.dirname(DS)
tn = json.load(open(os.path.join(DS, "inst", "extdata", "tokens", "teal_neue.json")))["custom_properties"]
bk = json.load(open(os.path.join(DS, "inst", "extdata", "tokens", "BlockR.json")))["custom_properties"]
keep = lambda s: s.startswith("html") or s.startswith("[data-tn-sec")
out = ["/* Neue design tokens (generated by tools/make_neue_tokens.py; do not edit by hand).",
       " * Source: teal_neue/inst/www/teal_neue.css (token rules only, values verbatim).",
       " * Layers: primitives (html:root) -> light / dark semantics (+ Bootstrap bridge --bs-*) -> section tints ->",
       " * user appearance attributes (data-tn-text | density | accent | corners | contrast). See inst/guides/neue/STYLEGUIDE.md. */", ""]
for sel, vals in tn.items():
    if not keep(sel) or "{@" in sel: continue
    out.append(sel.replace("\n", " ") + " {")
    out += ["  %s: %s;" % (k, re.sub(r"\s+", " ", v)) for k, v in vals.items()]
    out.append("}")
slate = bk['html[data-bs-theme="dark"]']
out += ["", "/* Alternative dark palette: BlockR's \"lifted slate\" (BlockR/inst/www/blockr.css). Opt in with",
        " * <html data-tn-dark=\"slate\">. Use one dark palette per product (inst/guides/neue/STYLEGUIDE.md section 2.3). */",
        'html[data-bs-theme="dark"][data-tn-dark="slate"] {']
diff = {k: v for k, v in slate.items() if tn['html[data-bs-theme="dark"]'].get(k) != v}
out += ["  %s: %s;" % (k, v) for k, v in diff.items()]
out += ["}", "", "/* BlockR canvas layer (blocks, wires), mapped onto the Neue tokens */"]
for sel in [s for s in bk if s.startswith(".bk-app") or s.startswith("html[data-bs-theme=\"dark\"] .bk-app") or s.startswith(".bk-cat-") or s.startswith(".bk-wk-")]:
    if "{@" in sel: continue
    out.append(sel.replace("\n", " ") + " {"); out += ["  %s: %s;" % (k, v) for k, v in bk[sel].items()]; out.append("}")
open(os.path.join(DS, "inst", "css", "neue-tokens.css"), "w").write("\n".join(out) + "\n")
print("neue-tokens.css:", sum(1 for l in out if l.strip().startswith("--")), "declarations;", len(diff), "slate overrides")
